export async function seedPlantao() {
  const instrutores = await instrutoresService.listar();

  for (const [nome, dias] of Object.entries(DADOS)) {
    const instrutor = instrutores.find((i) =>
      i.nome.toLowerCase().includes(nome.toLowerCase())
    );

    if (!instrutor) {
      console.warn(`Instrutor não encontrado: ${nome}`);
      continue;
    }

    const entradas = Object.entries(dias).flatMap(([dia, horarios]) =>
      (horarios ?? []).map((horario) => ({
        dia: dia as DiaSemanaPlantao,
        horario,
      }))
    );

    await plantaoService.definirEmMassa(instrutor.id, entradas);
    console.log(`✅ ${nome}: ${entradas.length} horários gravados`);
  }

  console.log("Concluído.");
}